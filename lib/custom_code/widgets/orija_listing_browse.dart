  @override
  void initState() {
    super.initState();
    final type = (widget.type ?? '').trim();
    final sub = (widget.subcategorySlug ?? '').trim();
    if (type == 'goods' || type == 'services') _f['type'] = type;
    if (sub.isNotEmpty && sub != 'null') _f['subcategory'] = sub;
    // Deep-linked with a starting sort (e.g. Explore's 'For You' See more) --
    // read straight off the route's query params, since the generated page
    // wrapper only forwards communityID/name/suvcategorySlug/type, not sort.
    final initialSort =
        GoRouterState.of(context).uri.queryParameters['sort'] ?? '';
    if (initialSort.isNotEmpty && initialSort != 'relevance') {
      _f['sort'] = initialSort;
    }
    // Orija Campus: opened for Accommodation (Explore's See more), the page
    // switches to accommodation mode: room types, areas, free now, rent.
    final cat = GoRouterState.of(context).uri.queryParameters['category'] ?? '';
    if (cat == 'hostels') {
      _rooms = true;
      _f['category'] = 'hostels';
      _loadRoomFilters();
    }
    _scroll.addListener(() {
      if (_scroll.hasClients &&
          _scroll.position.pixels > _scroll.position.maxScrollExtent - 320)
        _loadMore();
    });
    _load();
    _loadCommunityKind();
  }

