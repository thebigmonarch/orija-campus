                _titleBar(t),
                _communityTabs(t),
              ] else ...[
                _header(t),
                if (_showDashboard) _dashboardRow(t),
              ],
              if (_hasCommunityTitle && _commTab == 1)
                Expanded(
                  child: OrijaCommunity(
                    communityId: _community,
                    embedded: true,
                  ),
                )
              else ...[
                if (_hasCommunityTitle)
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 12, 16, 4),
                    child: _searchField(t),
                  ),
                _rooms ? _roomsBar(t) : _quickBar(t),
                if (_applied.isNotEmpty) _appliedRow(t),
                if (_refreshing)
                  LinearProgressIndicator(
                      minHeight: 2,
                      color: t.secondary,
                      backgroundColor: t.alternate),
                Expanded(child: _body(t)),
              ],
            ],
          ),
        ),
      ),
    );
  }

