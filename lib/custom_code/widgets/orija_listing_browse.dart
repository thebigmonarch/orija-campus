  String _duration(int h) {
    if (h < 24) return '$h hr${h == 1 ? '' : 's'}';
    final d = (h / 24).round();
    return '$d day${d == 1 ? '' : 's'}';
  }

  Widget _card(FlutterFlowTheme t, Map<String, dynamic> l, int i) {
    final store = l['store'] is Map
        ? Map<String, dynamic>.from(l['store'] as Map)
        : <String, dynamic>{};
    final service = l['type'] == 'services';
    final promoted = l['is_promoted'] == true;
    final price = (l['price'] as num?) ?? 0;
    final from = (l['starting_price'] as num?) ?? 0;
    final image = withListingWatermark((l['image'] as String?) ?? '') ?? '';
    final stock = (l['stock_quantity'] as num?)?.toInt();
    final negotiable =
        l['is_negotiable'] == true || l['pricing_type'] == 'negotiable';
    final rating = (store['rating'] as num?)?.toDouble();
    final reviews = (store['reviews'] as num?)?.toInt() ?? 0;
    final market = store['market'] is Map
        ? Map<String, dynamic>.from(store['market'] as Map)
        : null;
    final place = [store['city'], store['state']]
        .where((e) => '${e ?? ''}'.trim().isNotEmpty)
        .join(', ');
    final mode = switch (l['service_mode']) {
      'remote' => 'Remote',
      'at_buyer' => 'At your place',
      _ => 'At seller’s place'
    };

    return InkWell(
      borderRadius: BorderRadius.circular(14),
      onTap: () => _open(l),
      child: Container(
        clipBehavior: Clip.antiAlias,
        decoration: BoxDecoration(
          color: t.secondaryBackground,
          borderRadius: BorderRadius.circular(14),
          // Promoted listings stand out with a primary-colour border.
          border: Border.all(
              color: promoted ? t.primary : t.alternate,
              width: promoted ? 2 : 1),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            AspectRatio(
              aspectRatio: i % 3 == 0 ? 0.95 : (i % 3 == 1 ? 1.1 : 1.0),
              child: Stack(fit: StackFit.expand, children: [
                image.isEmpty
                    ? Container(
                        color: t.alternate,
                        child: Icon(
                            service
                                ? Icons.handyman_outlined
                                : Icons.image_outlined,
                            color: t.secondaryText,
                            size: 34))
                    : Image.network(image,
                        fit: BoxFit.cover,
                        errorBuilder: (_, __, ___) =>
                            Container(color: t.alternate)),
                Positioned(
                  top: 8,
                  left: 8,
                  child: Wrap(spacing: 4, children: [
                    if (promoted) _badge('Promoted', t.primary, Colors.white),
                    if (service)
                      _badge('Service', Colors.black54, Colors.white),
                  ]),
                ),
                Positioned(
                    top: 6,
                    right: 6,
                    child: OrijaListingSaveButton(
                        listingId: '${l['id']}', compact: true)),
              ]),
            ),
            Padding(
              padding: const EdgeInsets.fromLTRB(10, 10, 10, 10),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(crossAxisAlignment: CrossAxisAlignment.end, children: [
                    Flexible(
                      child: Text(
                          price > 0
                              ? (_rooms ? '${_naira(price)}/yr' : _naira(price))
                              : (from > 0
                                  ? 'From ${_naira(from)}'
                                  : 'Ask for a quote'),
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                          style: TextStyle(
                              color: t.secondary,
                              fontSize: 14.5,
                              fontWeight: FontWeight.w800)),
                    ),
                    if (negotiable)
                      Padding(
                          padding: const EdgeInsets.only(left: 5),
                          child: Text('Negotiable',
                              style: TextStyle(
                                  color: t.secondaryText, fontSize: 10.5))),
                  ]),
                  const SizedBox(height: 4),
                  Text('${l['title']}',
                      maxLines: 2,
                      overflow: TextOverflow.ellipsis,
                      style: TextStyle(
                          color: t.primaryText,
                          fontSize: 13,
                          fontWeight: FontWeight.w700,
                          height: 1.25)),
                  const SizedBox(height: 6),
                  Wrap(spacing: 6, runSpacing: 4, children: [
                    if (service) ...[
                      _tag(t, mode, Icons.place_outlined),
                      if ((l['turnaround_hours'] as num?) != null)
                        _tag(
                            t,
                            _duration((l['turnaround_hours'] as num).toInt()),
                            Icons.schedule_outlined),
                    ] else ...[
                      if (l['condition'] != null && l['condition'] != 'new')
                        _tag(
                            t,
                            '${'${l['condition']}'[0].toUpperCase()}${'${l['condition']}'.substring(1)}',
                            null),
                      if (stock != null && stock > 0 && stock <= 5)
                        _tag(t, 'Only $stock left', null, color: t.error),
                      if (stock != null && stock < 1)
                        _tag(t, 'Sold out', null, color: t.error),
                    ],
                  ]),
                  const SizedBox(height: 8),
                  Row(children: [
                    Flexible(
                        child: Text('${store['name'] ?? ''}',
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: TextStyle(
                                color: t.secondaryText,
                                fontSize: 11.5,
                                fontWeight: FontWeight.w600))),
                    if (store['verified'] == true)
                      Padding(
                          padding: const EdgeInsets.only(left: 3),
                          child: Icon(Icons.verified_rounded,
                              size: 13, color: t.secondary)),
                  ]),
                  if (market != null)
                    Padding(
                      padding: const EdgeInsets.only(top: 2),
                      child: Row(mainAxisSize: MainAxisSize.min, children: [
                        Icon(Icons.storefront_rounded,
                            size: 11, color: t.secondary),
                        const SizedBox(width: 3),
                        Flexible(
                          child: Text('${market['name'] ?? ''}',
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                              style: TextStyle(
                                  color: t.secondary,
                                  fontSize: 10.5,
                                  fontWeight: FontWeight.w600)),
                        ),
                        // badge_market (a market head's physical-market
                        // approval) is a different, lesser credential than
                        // real document-based verification -- it shouldn't
                        // show the same checkmark that implies that. The
                        // actual verified checkmark is next to the store
                        // name above.
                      ]),
                    ),
                  if (place.isNotEmpty || (rating != null && reviews > 0))
                    Padding(
                      padding: const EdgeInsets.only(top: 2),
                      child: Row(children: [
                        if (rating != null && reviews > 0) ...[
                          Icon(Icons.star_rounded,
                              size: 13, color: t.secondary),
                          const SizedBox(width: 2),
                          Text(rating.toStringAsFixed(1),
                              style: TextStyle(
                                  color: t.primaryText,
                                  fontSize: 11.5,
                                  fontWeight: FontWeight.w600)),
                          const SizedBox(width: 6)
                        ],
                        if (place.isNotEmpty)
                          Flexible(
                              child: Text(place,
                                  maxLines: 1,
                                  overflow: TextOverflow.ellipsis,
                                  style: TextStyle(
                                      color: t.secondaryText, fontSize: 11.5))),
                      ]),
                    ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

