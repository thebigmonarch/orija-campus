/// Browse listings, goods and services together: search, a few quick filters
/// (type, sort, price) and a Filters button that opens the full filter page.
/// Promoted listings get a border in the primary colour. It can be limited to
/// one community's stores, one sub-category, or one type. It scrolls itself.
