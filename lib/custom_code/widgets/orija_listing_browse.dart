  Future<void> _load({bool keepScroll = false}) async {
    final my = ++_req;
    setState(() {
      if (_items.isEmpty) {
        _loading = true;
      } else {
        _refreshing = true;
      }
      _error = null;
    });
    try {
      final res = await _db.rpc('browse_listings_v1', params: _params(0));
      if (!mounted || my != _req) return;
      if (res is Map && res['success'] == true) {
        setState(() {
          _items = ((res['results'] as List?) ?? const [])
              .map((e) => Map<String, dynamic>.from(e as Map))
              .toList();
          _hasMore = res['has_more'] == true;
          _total = (res['total_count'] as num?)?.toInt() ?? _items.length;
          _loading = false;
          _refreshing = false;
        });
        if (!keepScroll && _scroll.hasClients) _scroll.jumpTo(0);
      } else {
        setState(() {
          _loading = false;
          _refreshing = false;
          _error = 'Could not load listings. Pull down to try again.';
        });
      }
    } catch (_) {
      if (!mounted || my != _req) return;
      setState(() {
        _loading = false;
        _refreshing = false;
        _error = 'No connection. Pull down to try again.';
      });
    }
  }

  Future<void> _loadMore() async {
    if (!_hasMore || _loadingMore || _refreshing || _loading) return;
    final my = _req;
    setState(() => _loadingMore = true);
    try {
      final res =
          await _db.rpc('browse_listings_v1', params: _params(_items.length));
      if (!mounted || my != _req) return;
      if (res is Map && res['success'] == true) {
        final more = ((res['results'] as List?) ?? const [])
            .map((e) => Map<String, dynamic>.from(e as Map))
            .toList();
        final have = {for (final r in _items) '${r['id']}'};
        setState(() {
          _items = [
            ..._items,
            ...more.where((r) => !have.contains('${r['id']}'))
          ];
          _hasMore = res['has_more'] == true;
        });
      }
    } catch (_) {}
    if (mounted) setState(() => _loadingMore = false);
  }

  void _onSearch(String _) {
    setState(() {});
    _debounce?.cancel();
    _debounce = Timer(const Duration(milliseconds: 350), _load);
  }

  void _apply(void Function() change) {
    setState(change);
    _load();
  }

  Future<void> _openFilters() async {
    final payload = {
      ..._f,
      'search': _field.text.trim(),
      'communityId': _community
    };
    final res = await context.pushNamed(_kFiltersRoute,
        queryParameters: {'filters': jsonEncode(payload)});
    if (res is Map && mounted) {
      final next = Map<String, dynamic>.from(res);
      next.remove('search');
      next.remove('communityId');
      setState(() => _f = next);
      _load();
    }
  }

  int get _activeCount {
    var n = 0;
    for (final k in [
      'category',
      'subcategory',
      'state',
      'city',
      'minPrice',
      'maxPrice',
      'negotiable',
      'inStock',
      'verified',
      'minRating',
      'postedDays',
      'maxTurnaround'
    ]) {
      if (_f[k] != null) n++;
    }
    if (((_f['conditions'] as List?) ?? const []).isNotEmpty) n++;
    if (((_f['serviceModes'] as List?) ?? const []).isNotEmpty) n++;
    n += ((_f['specs'] as Map?) ?? const {}).length;
    return n;
  }

  /// One removable chip per applied filter.
  List<(String, VoidCallback)> get _applied {
    final out = <(String, VoidCallback)>[];
    void add(String label, List<String> keys) => out.add((
          label,
          () => _apply(() {
                for (final k in keys) {
                  _f.remove(k);
                }
              })
        ));
    // In accommodation mode the category is the page itself, not a filter.
    if (_f['category'] != null && !_rooms)
      add('Category: ${'${_f['category']}'.replaceAll('-', ' ')}',
          ['category', 'subcategory']);
    if (_f['subcategory'] != null && _f['category'] == null)
      add('Sub-category: ${'${_f['subcategory']}'.replaceAll('-', ' ')}',
          ['subcategory']);
    if (_f['state'] != null)
      add('${_f['state']}${_f['city'] != null ? ', ${_f['city']}' : ''}',
          ['state', 'city']);
    if (_f['state'] == null && _f['city'] != null)
      add('${_f['city']}', ['city']);
    if (_f['minPrice'] != null || _f['maxPrice'] != null) {
      add('${_f['minPrice'] != null ? _naira(_f['minPrice'] as num) : 'Any'} – ${_f['maxPrice'] != null ? _naira(_f['maxPrice'] as num) : 'Any'}',
          ['minPrice', 'maxPrice']);
    }
    for (final c in ((_f['conditions'] as List?) ?? const [])) {
      add('${'$c'[0].toUpperCase()}${'$c'.substring(1)}', ['conditions']);
    }
    if (((_f['serviceModes'] as List?) ?? const []).isNotEmpty)
      add('Service delivery', ['serviceModes']);
    if (_f['maxTurnaround'] != null)
      add('Within ${_f['maxTurnaround'] == 24 ? 'a day' : (_f['maxTurnaround'] == 72 ? '3 days' : 'a week')}',
          ['maxTurnaround']);
    if (_f['verified'] == true) add('Verified sellers', ['verified']);
    if (_f['minRating'] != null) add('${_f['minRating']}★ & up', ['minRating']);
    if (_f['negotiable'] == true) add('Negotiable', ['negotiable']);
    if (_f['postedDays'] != null)
      add(
          _f['postedDays'] == 1
              ? 'Last 24 hours'
              : 'Last ${_f['postedDays']} days',
          ['postedDays']);
    return out;
  }

  String _naira(num v) {
    final s = v.round().toString();
    final b = StringBuffer();
    for (var i = 0; i < s.length; i++) {
      if (i > 0 && (s.length - i) % 3 == 0) b.write(',');
      b.write(s[i]);
    }
    return '₦$b';
  }

  void _open(Map<String, dynamic> l) {
    final store = l['store'] is Map
        ? Map<String, dynamic>.from(l['store'] as Map)
        : <String, dynamic>{};
    // Desktop Shell rollout, Phase 4 (Pattern C). Desktop selects into the
    // split pane instead of pushing a route; mobile is unchanged below.
    if (OrijaDesktopShell.isDesktop(context)) {
      setState(() {
        _selectedListingId = '${l['id']}';
        _selectedStorefrontId = '${store['id']}';
      });
      return;
    }
    context.pushNamed(_kListingRoute,
        queryParameters: {
          'listingId': serializeParam('${l['id']}', ParamType.String),
          'storefrontId': serializeParam('${store['id']}', ParamType.String),
        }.withoutNulls);
  }

