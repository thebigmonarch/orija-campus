  Future<void> _loadRoomFilters() async {
    try {
      final info = await _db.rpc('get_my_school_agent_info');
      final types = await _db
          .from('subcategories')
          .select('slug, name')
          .eq('category_slug', 'hostels')
          .eq('is_active', true)
          .order('sort_order');
      if (!mounted) return;
      setState(() {
        if (info is Map)
          _roomAreas = [
            for (final a in (info['areas'] as List? ?? const [])) '$a'
          ];
        _roomTypes = [
          for (final x in types as List)
            {'slug': '${x['slug']}', 'name': '${x['name']}'}
        ];
      });
    } catch (_) {}
  }

